// Writes public/third-party-licenses.txt: the licence and licence text of
// every production dependency, plus the PlantUML stdlib bundles the site
// serves. MIT, BSD and Apache all require their notices to travel with the
// code, and the built site bundles that code.
//
// Usage: node scripts/collect-licenses.mjs [--summary]
// --summary prints a count per licence instead of writing the file.

import { execSync } from "node:child_process";
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
// A fixed command string: no user input reaches the shell.
const tree = JSON.parse(
  execSync("npm ls --omit=dev --all --long --json", { cwd: root, encoding: "utf8", maxBuffer: 64 * 1024 * 1024 }),
);

/** name@version -> package info, deduplicated across the tree. */
const packages = new Map();

function walk(node) {
  for (const dep of Object.values(node.dependencies ?? {})) {
    if (!dep.path || dep.extraneous) continue;
    const key = `${dep.name}@${dep.version}`;
    if (!packages.has(key)) {
      packages.set(key, readPackage(dep.path));
      walk(dep);
    }
  }
}

function readPackage(dir) {
  const pkg = JSON.parse(readFileSync(join(dir, "package.json"), "utf8"));
  const license =
    typeof pkg.license === "string"
      ? pkg.license
      : pkg.license?.type ?? pkg.licenses?.map((l) => l.type ?? l).join(" OR ") ?? "UNKNOWN";
  const repo = typeof pkg.repository === "string" ? pkg.repository : pkg.repository?.url;
  // Licence files, plus folders of them (ECharts keeps d3's licence in licenses/).
  const files = readdirSync(dir, { withFileTypes: true })
    .filter((e) => /^(licen[cs]e|copying|notice)/i.test(e.name))
    .flatMap((e) =>
      e.isDirectory() ? readdirSync(join(dir, e.name)).sort().map((f) => join(e.name, f)) : [e.name],
    );
  const text = files.map((f) => readFileSync(join(dir, f), "utf8").trim()).join("\n\n");
  // A few packages omit the field but ship a plain MIT licence file.
  const inferred = license === "UNKNOWN" && /^\s*(The )?MIT License/i.test(text) ? "MIT" : license;
  return { name: pkg.name, version: pkg.version, license: inferred, repo: repo?.replace(/^git\+/, ""), text };
}

walk(tree);

// Stdlib bundles carry their own licence in window.PLANTUML_STDLIB_INFO.
const stdlibDir = join(root, "public", "vendor", "plantuml-stdlib");
const stdlib = [];
if (existsSync(stdlibDir)) {
  for (const file of readdirSync(stdlibDir).filter((f) => f.endsWith(".min.js")).sort()) {
    const head = readFileSync(join(stdlibDir, file), "utf8").slice(0, 4000);
    const field = (k) => head.match(new RegExp(`${k}:"([^"]*)"`))?.[1];
    stdlib.push({
      file,
      name: field("display_name") ?? field("name") ?? file,
      license: field("license") ?? "see source",
      source: field("source") ?? "",
    });
  }
}

const sorted = [...packages.values()].sort((a, b) => a.name.localeCompare(b.name));

if (process.argv.includes("--summary")) {
  const counts = {};
  for (const p of sorted) counts[p.license] = (counts[p.license] ?? 0) + 1;
  console.log(`${sorted.length} production packages`);
  for (const [lic, n] of Object.entries(counts).sort((a, b) => b[1] - a[1])) console.log(`  ${n}\t${lic}`);
  console.log(`${stdlib.length} stdlib bundles`);
  for (const s of stdlib) console.log(`  ${s.license}\t${s.name}`);
  process.exit(0);
}

const rule = "-".repeat(78);
let out = `Third-party software in Figvex\n${rule}\n\n`;
out += "Figvex includes the open-source packages below. Each is listed with its\n";
out += "licence and, where the package ships one, the full licence text.\n";
out += "Generated by scripts/collect-licenses.mjs during the build.\n\n";

for (const p of sorted) {
  out += `${rule}\n${p.name} ${p.version}\nLicence: ${p.license}\n`;
  if (p.repo) out += `Source: ${p.repo}\n`;
  out += "\n" + (p.text || "(No licence file in the package; see the licence named above.)") + "\n\n";
}

