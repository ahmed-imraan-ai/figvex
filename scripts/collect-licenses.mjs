out += `${rule}\nComponents bundled inside @plantuml/core\n${rule}\n\n`;
for (const [name, license, source, notice] of embedded) {
  out += `${name}\nLicence: ${license}\nSource: ${source}\n${notice}\n\n`;
}

if (stdlib.length) {
  out += `${rule}\nPlantUML standard library bundles served by this site\n${rule}\n\n`;
  for (const s of stdlib) out += `${s.name} (${s.file})\nLicence: ${s.license}\n${s.source ? `Source: ${s.source}\n` : ""}\n`;
}

writeFileSync(join(root, "public", "third-party-licenses.txt"), out);
console.log(`[collect-licenses] ${sorted.length} packages, ${stdlib.length} stdlib bundles -> public/third-party-licenses.txt`);
